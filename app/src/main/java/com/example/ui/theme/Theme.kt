object GestoTheme {
    val colors: GestoThemeColors
        @Composable
        @ReadOnlyComposable
        get() = LocalGestoColors.current
}

@Composable
fun MyApplicationTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val gestoColors = if (darkTheme) DarkGestoColors else LightGestoColors
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme

    CompositionLocalProvider(LocalGestoColors provides gestoColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}
